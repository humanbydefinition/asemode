import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unicodeName, unicodeType } from 'unicode-name';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const output = resolve(root, 'src/unicode/names');
const unicodeNameVersion = JSON.parse(
	readFileSync(resolve(root, 'node_modules/unicode-name/package.json'), 'utf8')
).version;
const check = process.argv.includes('--check');
const planes = Array.from({ length: 17 }, () => []);
const labelRanges = [];
let rangeStart = null;
let rangeType = null;

/**
 * Finish the current Unicode label range and clear its state.
 * @param {number} end Inclusive final code point of the range.
 * @returns {void}
 */
function closeLabelRange(end) {
	if (rangeStart !== null) labelRanges.push([rangeStart, end, rangeType]);
	rangeStart = null;
	rangeType = null;
}

/**
 * Quote a Unicode name or label for a Lua string literal.
 * @param {string} value Text to quote.
 * @returns {string} Escaped Lua string literal.
 */
function luaString(value) {
	return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

/**
 * Render one Unicode plane as a Lua code-point-to-name table.
 * @param {Array<[number, string]>} entries Code points and names in order.
 * @returns {string} Generated Lua source.
 */
function sourceForPlane(entries) {
	return [
		`-- Generated by scripts/build/generate-unicode-names.mjs from unicode-name ${unicodeNameVersion}.`,
		'return {',
		...entries.map(([codepoint, name]) => `  [${codepoint}] = ${luaString(name)},`),
		'}',
		'',
	].join('\n');
}

for (let codepoint = 0; codepoint <= 0x10ffff; codepoint++) {
	const name = unicodeName(codepoint);
	const type = unicodeType(codepoint);
	const hasLabel = type !== 'Graphic' && type !== 'Format';

	if (name && !name.startsWith('<')) {
		planes[codepoint >>> 16].push([codepoint, name]);
	}

	if (hasLabel) {
		if (rangeType !== type) {
			closeLabelRange(codepoint - 1);
			rangeStart = codepoint;
			rangeType = type;
		}
	} else {
		closeLabelRange(codepoint - 1);
	}
}
closeLabelRange(0x10ffff);

const generated = new Map();
for (let plane = 0; plane < planes.length; plane++) {
	if (!planes[plane].length) continue;
	const name = `plane_${plane.toString(16).padStart(2, '0')}.lua`;
	generated.set(resolve(output, name), sourceForPlane(planes[plane]));
}
generated.set(
	resolve(root, 'src/unicode/name-label-ranges.lua'),
	[
		`-- Generated by scripts/build/generate-unicode-names.mjs from unicode-name ${unicodeNameVersion}.`,
		'return {',
		...labelRanges.map(([start, end, type]) => `  {${start}, ${end}, ${luaString(type)}},`),
		'}',
		'',
	].join('\n')
);

if (check) {
	const existing = new Set();
	if (existsSync(output)) {
		for (const file of readdirSync(output)) existing.add(resolve(output, file));
	}
	const errors = [];
	for (const [path, expected] of generated) {
		existing.delete(path);
		if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) errors.push(path);
	}
	for (const stale of existing) errors.push(stale);
	if (errors.length) {
		throw new Error(
			`Generated Unicode name data is stale: ${errors.map((path) => path.replace(`${root}/`, '')).join(', ')}`
		);
	}
	console.log(
		`Verified ${planes.reduce((sum, plane) => sum + plane.length, 0)} Unicode names and ${labelRanges.length} label ranges.`
	);
} else {
	mkdirSync(output, { recursive: true });
	for (const file of readdirSync(output)) {
		if (file.startsWith('plane_') && file.endsWith('.lua')) rmSync(resolve(output, file));
	}
	for (const [path, source] of generated) {
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, source);
	}
	console.log(
		`Generated ${planes.reduce((sum, plane) => sum + plane.length, 0)} Unicode names in ${generated.size - 1} lazy-loaded planes.`
	);
}
