import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, realpathSync, rmSync } from 'node:fs';
import { resolve, dirname, basename, relative, isAbsolute, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFontRegistry, loadFontIdentities, verifyFontIdentity } from './font-verification.mjs';

/**
 * Calculate the FNV-1a source hash stored with a bundled font.
 * @param {Uint8Array} bytes Font file bytes.
 * @returns {string} Eight-character lowercase hexadecimal hash.
 */
export function contentHash(bytes) {
	let hash = 2166136261;
	for (const byte of bytes) hash = Math.imul(hash ^ byte, 16777619) >>> 0;
	return hash.toString(16).padStart(8, '0');
}

/**
 * Check whether any locally supplied optional font exists in assets/fonts.
 * @param {string} root Project root containing the font registry and assets.
 * @returns {boolean} True when at least one optional font file is present.
 */
export function hasOptionalFonts(root) {
	const assets = resolve(root, 'assets/fonts');
	const fonts = loadFontRegistry(root);
	return fonts.some((entry) => entry.distribution === 'optional' && existsSync(resolve(assets, entry.file)));
}

/**
 * Generate bundled Lua font resources, or verify them without modifying files.
 * @param {string} root Project root containing the font registry and assets.
 * @param {boolean} [check=false] Report stale output instead of writing or removing files.
 * @param {'default'|'release'} [edition='default'] Font distribution edition to generate.
 * @returns {number} Number of registered fonts.
 * @throws {Error} If a registry entry is invalid or generated output is stale in check mode.
 */
export function generateFontResources(root, check = false, edition = 'default') {
	if (!['default', 'release'].includes(edition)) throw new Error(`Unknown edition: ${edition}`);
	const assets = resolve(root, 'assets/fonts');
	const fonts = loadFontRegistry(root);
	const golden = loadFontIdentities(root, edition === 'release');
	const verifiedOptional = new Map();
	if (edition === 'release') {
		const errors = [];
		for (const font of fonts.filter((entry) => entry.distribution === 'optional')) {
			const path = resolve(assets, font.file);
			if (!existsSync(path)) {
				errors.push(`missing ${font.file}`);
				continue;
			}
			const bytes = readFileSync(path);
			try {
				verifiedOptional.set(font.file, { bytes, ...verifyFontIdentity(font, bytes, golden, true) });
			} catch {
				errors.push(`identity mismatch ${font.file}`);
			}
		}
		if (errors.length) throw new Error(`Optional fonts: ${errors.join(', ')}`);
	}
	const ids = new Set(),
		files = new Set(),
		generated = new Map(),
		resources = [];
	/**
	 * Convert a value to its Lua-compatible JSON string literal.
	 * @param {string} value Text to quote.
	 * @returns {string} Quoted text.
	 */
	const quote = (value) => JSON.stringify(value);
	const banner = '-- Generated by scripts/build/generate-font-resources.mjs. Do not edit.\n';
	for (const font of fonts) {
		for (const field of ['id', 'name', 'file', 'author', 'authorUrl', 'sourceUrl']) {
			if (typeof font[field] !== 'string' || !font[field].trim()) throw new Error(`Missing font field: ${field}`);
		}
		if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(font.id) || ids.has(font.id))
			throw new Error(`Invalid or duplicate font ID: ${font.id}`);
		if (basename(font.file) !== font.file || !/^[^/\\]+\.ttf$/.test(font.file) || files.has(font.file))
			throw new Error(`Invalid or duplicate font file: ${font.file}`);
		for (const key of ['authorUrl', 'sourceUrl'])
			if (new URL(font[key]).protocol !== 'https:') throw new Error(`Use HTTPS for ${key}`);
		if (font.file === 'PublicPixel.ttf' || font.name === 'Public Pixel')
			throw new Error('Public Pixel is no longer bundled');
		ids.add(font.id);
		files.add(font.file);
		if (!['default', 'optional'].includes(font.distribution))
			throw new Error(`Invalid font distribution: ${font.id}`);
		if (font.distribution === 'optional' && !/^[a-f0-9]{64}$/.test(font.sourceSha256 || ''))
			throw new Error(`Missing font fingerprint: ${font.id}`);
		font.available = font.distribution === 'default' || edition === 'release';
		if (!font.available) continue;
		const path = resolve(assets, font.file);
		if (!existsSync(path)) throw new Error(`Missing font asset: ${font.file}`);
		const fromAssets = relative(realpathSync(assets), realpathSync(path));
		if (fromAssets === '..' || fromAssets.startsWith('..' + sep) || isAbsolute(fromAssets))
			throw new Error(`Font escapes asset directory: ${font.file}`);
		const cached = verifiedOptional.get(font.file);
		const bytes = cached ? cached.bytes : readFileSync(path);
		if (!bytes.length || bytes.length > 16 * 1024 * 1024) throw new Error(`Invalid font byte length: ${font.file}`);
		const verified = cached || verifyFontIdentity(font, bytes, golden);
		font.portableFont = verified.font;
		const chunks = [];
		for (let offset = 0; offset < bytes.length; offset += 64) {
			chunks.push(
				'  "' +
					[...bytes.subarray(offset, offset + 64)]
						.map((byte) => '\\' + String(byte).padStart(3, '0'))
						.join('') +
					'",'
			);
		}
		generated.set(
			resolve(root, `src/fonts/data/${font.id}.lua`),
			banner + 'return table.concat{\n' + chunks.join('\n') + '\n}\n'
		);
		resources.push(
			`  [${quote(font.id)}] = { bytes = require(${quote('src.fonts.data.' + font.id)}), byteLength = ${bytes.length}, sha256 = ${quote(verified.sha256)}, sourceHash = ${quote(contentHash(bytes))}, portableFont = { id = ${quote(verified.font.id)}, name = ${quote(verified.font.name || font.name)} } },`
		);
	}
	if (existsSync(resolve(assets, 'PublicPixel.ttf'))) throw new Error('Remove the Public Pixel asset');
	generated.set(
		resolve(root, 'src/fonts/bundled.lua'),
		banner +
			'return {\n' +
			fonts
				.map(
					(font) =>
						'  { ' +
						Object.entries(font)
							.map(
								([key, value]) =>
									`${key} = ${key === 'portableFont' ? `{ id = ${quote(value.id)}, name = ${quote(value.name || font.name)} }` : typeof value === 'boolean' ? String(value) : quote(value)}`
							)
							.join(', ') +
						' },'
				)
				.join('\n') +
			'\n}\n'
	);
	generated.set(resolve(root, 'src/fonts/resources.lua'), banner + 'return {\n' + resources.join('\n') + '\n}\n');
	const dataDir = resolve(root, 'src/fonts/data');
	const stale = existsSync(dataDir)
		? readdirSync(dataDir)
				.map((name) => resolve(dataDir, name))
				.filter((path) => !generated.has(path))
		: [];
	if (check) {
		const errors = [
			...stale,
			...[...generated]
				.filter(([path, source]) => !existsSync(path) || readFileSync(path, 'utf8') !== source)
				.map(([path]) => path),
		];
		if (errors.length)
			throw new Error(`Generated fonts are stale: ${errors.map((path) => relative(root, path)).join(', ')}`);
	} else {
		mkdirSync(dataDir, { recursive: true });
		for (const path of stale) rmSync(path);
		for (const [path, source] of generated) writeFileSync(path, source);
	}
	return fonts.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
	const check = process.argv.includes('--check');
	console.log(`${check ? 'Verified' : 'Generated'} ${generateFontResources(root, check)} font catalog entries.`);
}
