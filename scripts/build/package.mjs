import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync, cpSync, mkdtempSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { generateFontResources, hasOptionalFonts } from './generate-font-resources.mjs';
import yazl from 'yazl';

/**
 * Remove older Asemode archives and checksums while preserving other files.
 * @param {string} directory Release artifact directory.
 * @param {string} currentArchive Archive filename to retain.
 * @returns {void}
 */
export function pruneArchives(directory, currentArchive) {
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		if (
			entry.isFile() &&
			/^asemode-.+\.aseprite-extension(?:\.sha256)?$/.test(entry.name) &&
			entry.name !== currentArchive &&
			entry.name !== `${currentArchive}.sha256`
		) {
			rmSync(resolve(directory, entry.name));
		}
	}
}

/**
 * Build an extension archive and its checksum.
 * @param {string} root Project root containing package inputs.
 * @param {string} output Directory for release artifacts.
 * @param {'default'|'release'} [edition='default'] Font distribution edition.
 * @returns {Promise<void>} Resolves when the archive is written.
 */
async function build(root, output, edition = 'default') {
	mkdirSync(output, { recursive: true });
	const manifest = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
	writeFileSync(
		resolve(root, 'src/core/version.lua'),
		`-- Generated by scripts/build/package.mjs from package.json.\nreturn ${JSON.stringify(manifest.version)}\n`
	);
	/**
	 * List files under a package input in deterministic order.
	 * @param {string} path File or directory to inspect.
	 * @returns {string[]} Absolute file paths.
	 * @throws {Error} If an input cannot be read.
	 */
	function filesAt(path) {
		return statSync(path).isDirectory()
			? readdirSync(path)
					.sort()
					.flatMap((name) => filesAt(resolve(path, name)))
			: [path];
	}
	const registry = JSON.parse(readFileSync(resolve(root, 'assets/fonts/registry.json'), 'utf8'));
	const allowedFonts = new Set(
		registry
			.filter((font) => edition === 'release' || font.distribution === 'default')
			.map((font) => `src/fonts/data/${font.id}.lua`)
	);
	if (edition === 'release') {
		allowedFonts.add('src/fonts/data/FROGBLOCK-license.txt');
		allowedFonts.add('src/fonts/data/KITCHEN-SINK-license.txt');
	}
	const entries = [
		'src',
		'README.md',
		'LICENSE',
		'THIRD_PARTY_NOTICES.md',
		'assets/fonts/licenses',
		'CONTRIBUTING.md',
		'CODE_OF_CONDUCT.md',
		'SECURITY.md',
		'docs/guide/README.md',
		'docs/images/readme-header.png',
		'examples/textmode-tycoon',
	]
		.flatMap((name) => filesAt(resolve(root, name)))
		.map((path) => ({ name: relative(root, path).replaceAll('\\', '/'), path }))
		.filter(
			({ name }) =>
				name !== 'examples/textmode-tycoon/textmode-tycoon.aseprite' &&
				(!name.startsWith('src/fonts/data/') || allowedFonts.has(name))
		)
		.map(({ name, path }) => ({ name, bytes: readFileSync(path) }));
	// Do not ship npm development scripts as extension behavior.
	const { scripts, devDependencies, private: isPrivate, prettier: prettierConfig, ...extensionManifest } = manifest;
	extensionManifest.engines = { aseprite: '>=1.3.18.6' };
	entries.unshift({ name: 'package.json', bytes: Buffer.from(JSON.stringify(extensionManifest, null, 2) + '\n') });
	const zip = new yazl.ZipFile();
	for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
		zip.addBuffer(entry.bytes, entry.name, { mtime: new Date('1980-01-01T00:00:00Z'), mode: 0o100644 });
	}
	const chunks = [];
	zip.outputStream.on('data', (chunk) => chunks.push(chunk));
	const finished = new Promise((resolve, reject) => {
		zip.outputStream.on('end', resolve);
		zip.outputStream.on('error', reject);
	});
	zip.end();
	await finished;
	const archive = Buffer.concat(chunks);
	const filename = `asemode-${manifest.version}.aseprite-extension`;
	writeFileSync(resolve(output, filename), archive);
	const checksum = `${createHash('sha256').update(archive).digest('hex')}  ${filename}\n`;
	writeFileSync(resolve(output, `${filename}.sha256`), checksum);
	pruneArchives(output, filename);
	console.log(`Built ${filename}: ${entries.length} files, ${archive.length} bytes`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
	if (process.argv.length !== 2) throw new Error('Usage: package.mjs');
	const manifest = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
	writeFileSync(
		resolve(root, 'src/core/version.lua'),
		`-- Generated by scripts/build/package.mjs from package.json.\nreturn ${JSON.stringify(manifest.version)}\n`
	);
	const edition = hasOptionalFonts(root) ? 'release' : 'default';
	console.log(`Building ${edition === 'release' ? 'full' : 'default'} font package.`);
	if (edition === 'release') {
		const temp = mkdtempSync(resolve(tmpdir(), 'asemode-release-'));
		try {
			for (const name of [
				'src',
				'assets/fonts',
				'tests/fixtures/font-identities.json',
				'docs',
				'examples',
				'package.json',
				'README.md',
				'LICENSE',
				'THIRD_PARTY_NOTICES.md',
				'CONTRIBUTING.md',
				'CODE_OF_CONDUCT.md',
				'SECURITY.md',
			]) {
				const dest = resolve(temp, name);
				mkdirSync(dirname(dest), { recursive: true });
				cpSync(resolve(root, name), dest, { recursive: true });
			}
			generateFontResources(temp, false, 'release');
			cpSync(
				resolve(temp, 'assets/fonts/licenses/FROGBLOCK.txt'),
				resolve(temp, 'src/fonts/data/FROGBLOCK-license.txt')
			);
			cpSync(
				resolve(temp, 'assets/fonts/licenses/KITCHEN-SINK.txt'),
				resolve(temp, 'src/fonts/data/KITCHEN-SINK-license.txt')
			);
			await build(temp, resolve(root, 'dist'), 'release');
		} finally {
			rmSync(temp, { recursive: true, force: true });
		}
	} else await build(root, resolve(root, 'dist'), 'default');
}
